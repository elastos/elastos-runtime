/// A decode-only system has no encoder, so the suite needs a known-good box for it.
/// The suite FAILS when a decode-only system is registered without an entry here.
type DecodeOnlyVector = (ProtectionSystemId, fn(&CustodyProtectionHeader) -> Vec<u8>);

pub(crate) const DECODE_ONLY_VECTORS: &[DecodeOnlyVector] = &[(
    elastos_legacy_v0::ELASTOS_CUSTODY_LEGACY.id,
    elastos_legacy_vector,
)];

/// The legacy vector: the pool encoding of the header, under the legacy id (the
/// legacy adapter reads the pool data schema, "-v1").
fn elastos_legacy_vector(header: &CustodyProtectionHeader) -> Vec<u8> {
    let mut boxed = elastos_pool_v1::ELASTOS_CUSTODY_POOL
        .encode(header)
        .unwrap();
    boxed[12..28].copy_from_slice(elastos_legacy_v0::ELASTOS_CUSTODY_LEGACY.id.as_bytes());
    boxed
}

/// A header with letters in its hex fields, so an uppercase spelling differs.
pub(crate) fn sample_header(media_suite: CencMediaSuite) -> CustodyProtectionHeader {
    CustodyProtectionHeader::new(
        ContentAccessIdV1::new(KID).unwrap(),
        &CustodyPoolIdentityV1::new(Digest32::new([0xab; 32]), 512).unwrap(),
        &CustodyEpochIdentityV1::new(Digest32::new([0xcd; 32]), 512).unwrap(),
        &CustodyCommitteeAuthorizationIdentityV1::new(Digest32::new([0xef; 32]), 512).unwrap(),
        media_suite,
    )
}

/// A known-good box for `system`: its own encoding, or its decode-only vector.
pub(crate) fn sample_box(system: &ProtectionSystem, header: &CustodyProtectionHeader) -> Vec<u8> {
    if system.can_encode() {
        return system.encode(header).unwrap();
    }
    let (_, vector) = DECODE_ONLY_VECTORS
        .iter()
        .find(|(id, _)| *id == system.id)
        .unwrap_or_else(|| panic!("decode-only system {} has no conformance vector", system.id));
    vector(header)
}

fn assert_canonical_uuid(text: &str) {
    let parts: Vec<&str> = text.split('-').collect();
    assert_eq!(
        parts.iter().map(|part| part.len()).collect::<Vec<_>>(),
        [8, 4, 4, 4, 12],
        "{text}"
    );
    assert!(text
        .bytes()
        .all(|byte| byte == b'-' || byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte)));
}

/// Registry and writer invariants.
pub(crate) fn check_registry_invariants(ctx: &ProtectionContext<'_>) {
    let systems = ctx.registry().systems();
    for (index, system) in systems.iter().enumerate() {
        assert_canonical_uuid(&system.id.to_string());
        for other in &systems[index + 1..] {
            assert_ne!(system.id, other.id);
            assert_ne!(system.scheme, other.scheme);
        }
    }
    assert_eq!(
        systems.iter().filter(|system| !system.is_custody()).count(),
        1,
        "exactly one Common system"
    );
    assert!(!ctx.registry().common().is_custody());
    let writer = ctx.writer();
    assert!(ctx.registry().lookup(writer.id.as_bytes()).is_some());
    assert!(writer.is_custody() && writer.can_encode());
    // Only the writer encodes: every other system is decode-only.
    for system in systems.iter().filter(|system| system.can_encode()) {
        assert_eq!(
            system.id, writer.id,
            "{} encodes but is not the writer",
            system.id
        );
    }
}

/// The refusal battery, generated by mutating a good box of `system`.
fn check_refusals(system: &ProtectionSystem, good: &[u8]) {
    let parsed = parse_pssh_v1(good).expect("a custody sample is a v1 box");
    let cid = parsed.kids[0];
    let rebuild = |kids: &[[u8; 16]], data: &[u8]| build_pssh_v1(system.id.as_bytes(), kids, data);
    let refused = |label: &str, boxed: &[u8]| {
        assert!(
            system.decode(boxed).is_err(),
            "{} accepted: {label}",
            system.id
        )
    };

    // The wrong system id, passed directly.
    let mut wrong_id = good.to_vec();
    wrong_id[27] ^= 0x01;
    refused("wrong system id", &wrong_id);
    refused("two KIDs", &rebuild(&[cid, cid], &parsed.data));
    refused(
        "KID differs from the declared id",
        &rebuild(&[[0x99; 16]], &parsed.data),
    );
    refused("no KID", &rebuild(&[], &parsed.data));
    let mut v0 = good.to_vec();
    v0[8] = 0;
    refused("box version 0", &v0);
    refused("truncated", &good[..good.len() - 1]);
    refused("empty", &[]);
    let mut slack = good.to_vec();
    let grown = (slack.len() as u32 + 8).to_be_bytes();
    slack[0..4].copy_from_slice(&grown);
    slack.extend_from_slice(&[0u8; 8]);
    refused("slack after Data", &slack);
    refused("Data over 4096 bytes", &rebuild(&[cid], &vec![b' '; 4097]));
    refused(
        "Data is not the payload",
        &rebuild(&[cid], b"not-json-at-all"),
    );

    // Edits to a JSON payload (every Elastos system reads the Data v1 JSON).
    if let Ok(json) = serde_json::from_slice::<serde_json::Value>(&parsed.data) {
        let edited = |label: &str, edit: &dyn Fn(&mut serde_json::Value)| {
            let mut json = json.clone();
            edit(&mut json);
            refused(label, &rebuild(&[cid], &serde_json::to_vec(&json).unwrap()));
        };
        edited("unknown field", &|json| {
            json["extra"] = serde_json::json!(1)
        });
        edited("uppercase hex", &|json| {
            let hex = json["custody_pool_sha256"].as_str().unwrap().to_uppercase();
            json["custody_pool_sha256"] = serde_json::json!(hex);
        });
        edited("unknown scheme name", &|json| {
            json["protection_scheme"] = serde_json::json!("cenc:conformance-unknown-scheme");
        });
        edited("unknown data schema", &|json| {
            json["schema"] = serde_json::json!("elastos.protected-content.cenc-pssh-data/v0");
        });
    }
}

/// An init segment carrying a Common box and the given custody boxes.
fn v2_init_with(ctx: &ProtectionContext<'_>, custody: Vec<Vec<u8>>) -> Vec<u8> {
    let mut pssh_at_end = vec![ctx.registry().common().encode_kid_list(&KID).unwrap()];
    pssh_at_end.extend(custody);
    let mut spec = InitSpec::protected(V, 8);
    spec.pssh_at_end = pssh_at_end;
    init(&spec)
}

fn v1_init_with(custody: Vec<Vec<u8>>) -> Vec<u8> {
    let mut spec = InitSpec::protected(V, 8);
    spec.pssh_at_end = custody;
    init(&spec)
}

/// Everything a custody system must satisfy, against `ctx`'s registry.
pub(crate) fn check_custody_adapter(ctx: &ProtectionContext<'_>, system: &ProtectionSystem) {
    assert!(system.is_custody());
    let registry = ctx.registry();
    let v2_header = sample_header(CencMediaSuite::DashV2);
    let v1_header = sample_header(CencMediaSuite::Fmp4V1);
    let v2_box = sample_box(system, &v2_header);
    let v1_box = sample_box(system, &v1_header);

    // Decoding gives the header back, and the registry resolves the box to it.
    assert_eq!(system.decode(&v2_box).unwrap(), v2_header);
    assert_eq!(system.decode(&v1_box).unwrap(), v1_header);
    let (id, decoded) = registry.decode_custody(&v2_box).unwrap();
    assert_eq!((id, decoded), (system.id, v2_header));
    assert!(matches!(
        registry.classify(system.id.as_bytes()),
        ProtectionClass::Custody(found) if found.id == system.id
    ));
    if system.can_encode() {
        assert_eq!(system.encode(&v2_header).unwrap(), v2_box);
    } else {
        assert!(system.encode(&v2_header).is_err());
    }
    check_refusals(system, &v2_box);

    // Embedded in a V2 init: validates and is reported as this system.
    let segment = crate::media::v2_tests::protect_in(ctx, V, &[]).segment;
    let layout = validate_in(ctx, &v2_init_with(ctx, vec![v2_box.clone()]), &segment).unwrap();
    assert_eq!(layout.protection_system(), Some(system.id));
    assert_eq!(layout.protection_header(), Some(&v2_header));
    // The V1 suite does not belong in a V2 init.
    assert!(validate_in(ctx, &v2_init_with(ctx, vec![v1_box.clone()]), &segment).is_err());

    // Alone in a V1 init: validates.
    let v1_init = v1_init_with(vec![v1_box.clone()]);
    let layout = validate_cenc_fmp4_media_structure_in(
        ctx,
        &v1_init,
        std::slice::from_ref(&v1_segment()),
        CencLayoutProfile::V1,
    )
    .unwrap();
    assert_eq!(layout.protection_system(), Some(system.id));
    // The V2 suite does not belong in a V1 init.
    assert!(validate_cenc_fmp4_media_structure_in(
        ctx,
        &v1_init_with(vec![v2_box.clone()]),
        std::slice::from_ref(&v1_segment()),
        CencLayoutProfile::V1,
    )
    .is_err());

    // Together with any custody box, itself included, in one init: refused.
    for other in registry.systems().iter().filter(|other| other.is_custody()) {
        let other_box = sample_box(other, &v2_header);
        assert!(validate_in(
            ctx,
            &v2_init_with(ctx, vec![v2_box.clone(), other_box.clone()]),
            &segment
        )
        .is_err());
        assert!(validate_in(
            ctx,
            &v2_init_with(ctx, vec![other_box, v2_box.clone()]),
            &segment
        )
        .is_err());
    }

    // A foreign extra may not carry this system's id.
    let clear_init = init(&InitSpec::clear(V));
    let layout = ValidatedClearFmp4MediaSessionLayoutV1::new_with_profile(
        &clear_init,
        CencLayoutProfile::V2,
    )
    .unwrap();
    let as_extra = build_pssh_v1(system.id.as_bytes(), &[], b"x");
    assert!(as_extra.len() <= MAX_PSSH_BOX_BYTES_V2);
    assert!(layout
        .rewrite_protected_init_v2_in(ctx, &clear_init, &v2_header, &[as_extra])
        .is_err());

    // The MPD names this system with its scheme.
    let mpd = build_cenc_dash_mpd_v2_in(
        ctx,
        &[CencDashMpdRenditionV2 {
            protected_init: &v2_init_with(ctx, vec![v2_box]),
            segments: &[CencDashMpdSegmentV2 {
                timeline: Fmp4SegmentTimelineV2 {
                    decode_time: 0,
                    duration: u64::from(TIMESCALE),
                },
                bytes: segment.len() as u64,
            }],
        }],
    )
    .unwrap();
    assert!(
        mpd.contains(&format!(
            "<ContentProtection schemeIdUri=\"urn:uuid:{}\" value=\"{}\">",
            system.id, system.scheme
        )),
        "{mpd}"
    );
}

/// Under a context whose writer is `ctx.writer()`, both writers produce inits that
/// re-validate and carry the writer's id.
pub(crate) fn check_writers(ctx: &ProtectionContext<'_>) {
    let writer = ctx.writer();
    let carries = |init: &[u8]| {
        init.windows(16)
            .any(|window| window == writer.id.as_bytes())
    };

    let v2 = protect_in(ctx, V, &[]);
    assert!(carries(&v2.init));
    let layout = validate_in(ctx, &v2.init, &v2.segment).unwrap();
    assert_eq!(layout.protection_system(), Some(writer.id));

    let clear_init = init(&InitSpec::clear(V));
    let session = ValidatedClearFmp4MediaSessionLayoutV1::new(&clear_init).unwrap();
    let v1_header = sample_header(CencMediaSuite::Fmp4V1);
    let v1_init = session
        .rewrite_protected_init_in(ctx, &clear_init, &v1_header)
        .unwrap();
    assert!(carries(&v1_init));
    let layout = validate_cenc_fmp4_media_structure_in(
        ctx,
        &v1_init,
        std::slice::from_ref(&v1_segment()),
        CencLayoutProfile::V1,
    )
    .unwrap();
    assert_eq!(layout.protection_system(), Some(writer.id));
    assert_eq!(layout.protection_header(), Some(&v1_header));
}

/// Every check, over every system of `ctx`'s registry, and the writers under every
/// system that can encode.
pub(crate) fn run_over(ctx: &ProtectionContext<'_>) {
    check_registry_invariants(ctx);
    for system in ctx.registry().systems().iter().filter(|s| s.is_custody()) {
        check_custody_adapter(ctx, system);
    }
    for system in ctx.registry().systems().iter().filter(|s| s.can_encode()) {
        check_writers(&ProtectionContext::new(ctx.registry(), system));
    }
}

#[test]
fn production_registry_passes_the_conformance_suite() {
    run_over(&PROTECTION);
}
